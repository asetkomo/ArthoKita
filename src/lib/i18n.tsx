const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (s: string) => string }>({
  lang: "id",
  setLang: () => {},
  t: (s) => s,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("id");
  useEffect(() => {
    try {
      const v = localStorage.getItem("dk-lang");
      if (v === "en" || v === "id") setLangState(v);
    } catch {
      /* ignore */
    }
  }, []);
  const setLang = (l: Lang) => {
    try {
      localStorage.setItem("dk-lang", l);
    } catch {
      /* ignore */
    }
    setLangState(l);
  };
  const t = (s: string) => (lang === "en" ? DICT[s] ?? s : s);
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}

export function useI18n() {
  return useContext(LangContext);
}
